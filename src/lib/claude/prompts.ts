// "1-1-1-2"のようなコーナー通過順文字列を数値配列にパースする共通ヘルパー。
// JV-DataのSEレコードにも4コーナー分の通過順位(corner1〜4_jyuni)という同種の構造化データは
// あるが、こちらも「どの馬が何番手を通ったか」という数値情報のみで、不利・進路取りを記述した
// 自由文フィールドは存在しない(2026-07-24、scripts/jvlink/parse_records.pyのparse_corner_info実装で
// 確認済み。corner/syukaisu/jyuni=数値・通過順のみ)。そのためJV-Link経由に切り替えても
// 「有利不利」の確定情報が得られるわけではなく、netkeiba由来のcorner_positionsと本質的に同じ
// 種類の推測材料にしかならない。
function parseCornerPositions(cornerPositions: string | null): number[] {
  if (!cornerPositions) return [];
  return cornerPositions
    .split(/[-–]/)
    .map((s) => Number(s.trim()))
    .filter((n) => Number.isFinite(n) && n > 0);
}

// コーナー通過順(例 "1-1-1-2")と頭数から脚質を機械推定する。フロック(まぐれ)警戒のため、
// 「前走は逃げてスローで残っただけ=展開依存の好走」を、LLMが生のコーナー文字列を解釈しなくても
// 判定できるよう、明示的なラベルにして渡す(2026-07-18)。pace_markはバックフィル分がほぼ空
// (per-horseページにレースペースが載らないため)だが、corner_positionsは99%充足しているため
// こちらから導出するのが実用的。あくまで簡易推定である旨はrunning_style_note側で明示する。
function inferRunningStyle(
  cornerPositions: string | null,
  entryCount: number | null,
): string | null {
  const positions = parseCornerPositions(cornerPositions);
  if (positions.length === 0) return null;
  const firstPos = positions[0];
  // 序盤の位置取り(先頭2コーナー平均)で脚質を判定する。最終コーナーは追い上げ後の位置なので使わない。
  const early = positions.slice(0, 2);
  const earlyAvg = early.reduce((a, b) => a + b, 0) / early.length;
  // 頭数不明時は暫定14頭として正規化(概算)。
  const field = entryCount && entryCount > 0 ? entryCount : 14;
  const ratio = earlyAvg / field;
  if (firstPos === 1 && ratio <= 0.25) return "逃げ";
  if (ratio <= 0.35) return "先行";
  if (ratio <= 0.7) return "差し";
  return "追込";
}

// 枠番(post_position)×全コーナーの通過順(corner_positions)から「外を回された可能性」を機械推定する。
// netkeibaの過去走データにもJV-Dataにも映像・回顧コメントの類は一切含まれず(2026-07-24確認、
// parseCornerPositionsのコメント参照)、past_performances.trouble_noteは常にnull(どのスクリプトも
// 書き込んでいない=未実装のまま放置されていた列)。映像が見られない以上確定的な判定はできないため、
// 単発の「序盤位置」だけでなく、全コーナーを通じてレース中ずっと中団より前の(=馬群の壁の中に
// 収まれず被されなかった)位置を保っていたかまで見て精度を上げる。外枠発走で、かつ記録された
// 全コーナーで「中団より前目の位置取りを維持し続けた」馬は、内で脚を溜める形が取れず、
// レースの大半を外を回らされ続けていた可能性が高いと判断する。序盤だけ前にいて早々に下げた馬
// (=一時的に前を取っただけ)はこの限りではないため対象外とする。あくまで推測であり確定情報では
// ない旨は呼び出し側(prompts.ts本文)で明示する。
function inferWideTripRisk(
  postPosition: number | null,
  cornerPositions: string | null,
  entryCount: number | null,
): boolean | null {
  if (!postPosition) return null;
  const positions = parseCornerPositions(cornerPositions);
  if (positions.length === 0) return null;
  const isOuterPost = postPosition >= 6; // 8枠制のうち外3枠を想定
  if (!isOuterPost) return false;
  const field = entryCount && entryCount > 0 ? entryCount : 14;
  // 記録された全コーナーで中団(頭数の50%以内)より前めの位置を維持し続けていたか。
  // 序盤だけ前にいて後半下げたケースは対象外にするため、全コーナーの条件にしている。
  const stayedForwardThroughout = positions.every((p) => p / field <= 0.5);
  return stayedForwardThroughout;
}

// 良・稍重(通常)と重・不良(重馬場)での複勝率を比較し、「重馬場巧者/不良馬場を苦手とする傾向」を
// 機械判定する(2026-08-05、ユーザー要望で新設)。past_performances全体の約17%程度しか重・不良の
// 出走が無い(2026-08-04のトラックバイアス分析時に確認)ため、大半の馬は判定不能になる想定。
// サンプル不足を「互角」と誤読させないよう、最低出走数に満たない場合は明示的に判定不能の文言を返す。
const HEAVY_TRACK_CONDITIONS = new Set(["重", "不良"]);
const MIN_HEAVY_STARTS = 3;
const HEAVY_TRACK_APTITUDE_THRESHOLD_POINTS = 15;

function computeHeavyTrackAptitude(pastPerformances: PastPerformanceRow[]): string {
  const withResult = pastPerformances.filter(
    (pp): pp is PastPerformanceRow & { track_condition: string; finish_position: number; entry_count: number } =>
      !!pp.track_condition && pp.finish_position != null && pp.finish_position > 0 && !!pp.entry_count,
  );
  const heavy = withResult.filter((pp) => HEAVY_TRACK_CONDITIONS.has(pp.track_condition));
  const normal = withResult.filter((pp) => !HEAVY_TRACK_CONDITIONS.has(pp.track_condition));
  if (heavy.length < MIN_HEAVY_STARTS) {
    return `重・不良馬場での出走実績が少なく判定不能(${heavy.length}走)`;
  }
  const placeRatePct = (rows: typeof heavy) =>
    Math.round((rows.filter((r) => r.finish_position <= 3).length / rows.length) * 100);
  const heavyRate = placeRatePct(heavy);
  if (normal.length === 0) {
    return `重馬場巧拙は評価保留(重・不良${heavy.length}走 複勝率${heavyRate}%、比較用の通常馬場データなし)`;
  }
  const normalRate = placeRatePct(normal);
  const diff = heavyRate - normalRate;
  const label =
    diff >= HEAVY_TRACK_APTITUDE_THRESHOLD_POINTS
      ? "重馬場巧者"
      : diff <= -HEAVY_TRACK_APTITUDE_THRESHOLD_POINTS
        ? "重馬場を苦手とする傾向"
        : "馬場による複勝率の大差なし";
  return `${label}(重・不良${heavy.length}走 複勝率${heavyRate}% 対 良・稍重${normal.length}走 複勝率${normalRate}%)`;
}

